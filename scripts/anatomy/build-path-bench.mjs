import fs from 'node:fs';
import * as k from './iso-kit.mjs';
// Figure: a mathematical tracing bench. Five y-carriages pick points of q=t+a sin(pi t).
// 68 solids: 8 foot/pads + base + 4 rim + 4 fasteners + 10 fixed-clamp pieces
// + 5*(2 rails + 2 stops + ruler + 3 carriage pieces) + label plate.
const W=660,H=360;
const P=k.fitProjection(k.boxCorners({x:-180,y:-115,w:360,d:210,r:8},-20,14),W,H,{pad:34,azimuth:55,elevation:44});
const parts=[];const moving=[];let count=0;
const box=(out,x,y,w,d,z,h,tone='mid',lit=false)=>{count++;out.push(k.solidSvg(k.slabOf({x,y,w,d,r:Math.min(1.2,w/4,d/4)},z,h,P,3,.5),{tone,lit}));};
const plate={x:-180,y:-115,w:360,d:210,r:8};
parts.push(`<path class="iso-halo" d="${k.haloOf(plate,-20,8,P)}"/>`);
for(const [x,y] of k.corners(plate,20).sort((a,b)=>k.depthOf([...a,0],P)-k.depthOf([...b,0],P))){box(parts,x-8,y-8,16,16,-20,4,'lo');box(parts,x-6,y-6,12,12,-16,6,'lo');}
box(parts,-180,-115,360,210,-10,10,'lo');
for(const [x,y,w,d] of [[-173,-108,346,3],[-173,85,346,3],[-173,-105,3,190],[170,-105,3,190]])box(parts,x,y,w,d,0,1,'lo');
for(const [x,y] of k.corners(plate,12)){box(parts,x-3,y-3,6,6,0,1,'mid');parts.push(k.dotsSvg([k.iso([x,y,1],P)],{size:.5,tone:'hi'}));}
// All rails lie below the carriage plane, so they paint before the moving parts.
const nodes=[1,2,3,4,5].map(j=>j/6);
for(const t of nodes){const x=-150+300*t,y=-65+100*t;
 for(const dx of [-7,4])box(parts,x+dx,-101,3,181,0,2,'mid');
 for(const sy of [-105,80]){box(parts,x-10,sy,20,4,0,5,'mid');parts.push(k.dotsSvg([k.iso([x,sy+2,5],P)],{size:.5,tone:'hi'}));}
 box(parts,x-3,-101,6,181,0,.5,'lo');
 for(let sy=-95,j=0;sy<79;sy+=5,j++)parts.push(k.lineSvg(k.lineOnTop([x-3,sy],[x-3+(j%5===0?4.5:2.3),sy],.5,P),{tone:j%5===0?'mid':'lo'}));
 const art=[];box(art,x-10,y-8,20,16,2,4,'mid');box(art,x-5,y-5,10,10,6,3,'hi');box(art,x-2.5,y-2.5,5,5,9,1,'hi');
 art.push(k.dotsSvg([k.iso([x,y,10],P)],{size:.7,tone:'hi'}));
 moving.push({t,art:art.join(''),origin:k.iso([x,y,10],P)});
}
const fixtures=[];
for(const [x,y] of [[-150,-65],[150,35]]){box(fixtures,x-12,y-11,24,22,0,3,'mid');box(fixtures,x-8,y-7,16,14,3,5,'hi');box(fixtures,x-9,y-8,18,5,8,2,'mid');box(fixtures,x-9,y+3,18,5,8,2,'mid');box(fixtures,x-2,y-2,4,4,8,2,'hi');fixtures.push(k.dotsSvg([k.iso([x-6,y-5.5,10],P),k.iso([x+6,y+5.5,10],P)],{size:.5,tone:'hi'}));}
box(parts,-165,59,43,17,0,.8,'lo');
for(const [yy,len] of [[63,30],[67,21],[71,26]])parts.push(k.lineSvg(k.lineOnTop([-160,yy],[-160+len,yy],.8,P),{tone:'lo',free:true}));
if(count!==68)throw Error(`Expected 68 purposeful solids, got ${count}`);
const source=`// Generated by scripts/anatomy/build-path-bench.mjs; Anatomy MIT kit.\nexport const staticBench=${JSON.stringify(parts.join(''))};\nexport const fixtures=${JSON.stringify(fixtures.join(''))};\nexport const carriages=${JSON.stringify(moving)};\nexport const projection=${JSON.stringify(P)};\nexport const parts=${count};\n`;
fs.writeFileSync(new URL('../../src/sections/widgets/path-bench-geometry.ts',import.meta.url),source);
// Standalone critic pages reuse the exact geometry, only for visual and line-end QA.
const curve=a=>k.pathOf(Array.from({length:181},(_,j)=>{const t=j/180;return k.iso([-150+300*t,-65+100*(t+a*Math.sin(Math.PI*t)),10],P);}));
const states=[-.7,0,.7];
for(const theme of ['light','dark']){
const body=states.map(a=>k.plateHtml({fig:'图解',title:'固定端点路径描线台',hint:'改变中间形状，两端固定',readout:`a = ${a.toFixed(2)}`,keys:[{mark:'lit',label:'所选路径'},{mark:'dotted',label:'直线路径'}],caption:'有限路径族的计算插画；不是粒子运动的记录。',body:k.figureSvg({width:W,height:H,label:'固定端点路径描线台',body:parts.join('')+fixtures.join('')+moving.map(({t,art})=>`<g transform="${k.translateAlong(P,[0,100*a*Math.sin(Math.PI*t),0])}">${art}</g>`).join('')+k.lineSvg(curve(0),{tone:'lo',dotted:true})+k.lineSvg(curve(a),{tone:'lit'})})})).join('');
fs.writeFileSync(new URL(`../../qa/path-bench-${theme}.html`,import.meta.url),k.pageHtml({title:'描线台图解审查',theme,body,width:760}).replace('lang="en"','lang="zh-CN"'));
}
console.log(`Path bench: ${count} solids, two critic pages, three boundary poses each.`);
