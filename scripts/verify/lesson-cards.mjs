import assert from 'node:assert/strict';
import {createElement as h, Fragment, isValidElement} from 'react';
import {splitCards,groupCards,nodeText} from '../../src/lesson/cards.ts';
const Experiment=()=>null, Eq=()=>null, Definition=()=>null;
const kinds=new Map([[Experiment,'experiment'],[Definition,'definition']]);
const math=new Set([Eq]);
const source=h(Fragment,null,h('p',null,'开始'),h('h3',null,'一个概念'),h('p',null,'甲'.repeat(250)),h('p',null,'乙'.repeat(250)),h('p',null,'所以：'),h(Eq,{id:'eq-test'},'A=B'),h(Experiment,{title:'实验',id:'lab'},h('p',null,'可操作的模型')),h('p',{className:'text-sm text-slate-500 dark:text-slate-400'},'来源'),h('h3',{id:'sec-sub'},'新结论'),h(Definition,{id:'env-test',label:'1 (定义)'},'数学定义'));
const cards=splitCards(source,'1.1','向量',kinds,math);
assert.equal(cards.filter(c=>c.kind==='experiment').length,1);
assert.equal(cards.find(c=>c.kind==='experiment').title,'实验');
assert.ok(nodeText(cards.find(c=>c.kind==='experiment').nodes).includes('来源'));
assert.ok(cards.find(c=>c.anchors.includes('eq-test')).nodes.some(n=>nodeText(n)==='所以：'));
assert.ok(cards.find(c=>c.anchors.includes('sec-sub')).anchors.includes('env-test'));
assert.ok(!cards.some(c=>c.nodes.length===1&&nodeText(c.nodes[0])==='新结论'));
const text=cards.map(c=>nodeText(c.nodes)).join('');for(const item of ['开始','甲'.repeat(250),'乙'.repeat(250),'所以：','A=B','可操作的模型','数学定义'])assert.equal(text.split(item).length-1,1,item);
assert.equal(new Set(cards.map(c=>c.id)).size,cards.length);
console.log('lesson-cards: bounded groups, formula lead-ins, standalone experiments, source notes, heading anchors and content preservation passed');
const long=h(Definition,{id:'env-long',label:'2 (长例子)'},...Array.from({length:14},(_,i)=>h('p',{key:i},'段落'+i+'内容'.repeat(80))),h(Eq,{id:'eq-inner'},'X=Y'));
const pieces=splitCards(long,'1.8','例子',kinds,math);
assert.ok(pieces.length>2);
assert.equal(pieces.flatMap(c=>c.anchors).filter(x=>x==='env-long').length,1);
assert.equal(pieces.flatMap(c=>c.anchors).filter(x=>x==='eq-inner').length,1);
for(let i=0;i<14;i++)assert.equal(pieces.map(c=>nodeText(c.nodes)).join('').split('段落'+i+'内容').length-1,1);
console.log('lesson-cards: long source examples split without duplicating source anchors or losing paragraphs');
const Model=()=>null;
const lab=h(Experiment,{title:'改变一个参数'},h(Model,{id:'model-anchor'}),h('p',null,'实验后的观察与解释'));
const labParts=splitCards(lab,'1.2','实验',kinds,math);
assert.equal(labParts.length,2);assert.equal(labParts[0].kind,'experiment');assert.equal(labParts[1].kind,'concept');assert.ok(labParts[0].anchors.includes('model-anchor'));assert.equal(nodeText(labParts[1].nodes),'实验后的观察与解释');
console.log('lesson-cards: experiment controls and consolidation get separate cards, preserving their anchors and prose');
const grouped=groupCards(cards);
const containsNode=(tree,node)=>tree===node||Array.isArray(tree)&&tree.some(child=>containsNode(child,node))||isValidElement(tree)&&containsNode(tree.props.children,node);
assert.ok(grouped.length<cards.length);
for(const original of cards){
 const owner=grouped.find(c=>c.id===original.id||c.anchors.includes(original.id));
 assert.ok(owner,'old card link lost: '+original.id);
 for(const anchor of original.anchors)assert.ok(owner.anchors.includes(anchor),'source anchor lost: '+anchor);
 for(const node of original.nodes)assert.ok(containsNode(owner.nodes,node),'content node lost');
}
assert.equal(grouped.find(c=>c.kind==='experiment'),cards.find(c=>c.kind==='experiment'));
const simple=Array.from({length:7},(_,i)=>({id:'old-'+i,sectionId:'1.1',title:'主题 '+i,kind:i===3?'quiz':'concept',nodes:[h('p',null,'解释'+i)],anchors:[]}));
const packed=groupCards(simple);
assert.equal(packed.length,3);assert.equal(packed[0].topics,3);assert.equal(packed[1].kind,'quiz');assert.equal(packed[2].topics,3);
assert.ok(packed[0].anchors.includes('old-2'));assert.equal(packed[0].nodes.length,3);
const heavy=simple.slice(0,2).map(c=>({...c,nodes:[h('p',null,'甲'.repeat(500))]}));assert.equal(groupCards(heavy).length,2);
console.log('lesson-cards: complete topic groups reduce paging, preserve all original nodes/links, and keep experiments/quizzes separate');
